import { describe, expect, it } from "vitest";
import { buildDateGuide } from "./date-guide";

describe("buildDateGuide: 기준일 2026-10-30(금)", () => {
  const g = buildDateGuide("2026-10-30");
  it("날짜 → 말: 요일 칸 세기 대신 그대로 찾는다", () => {
    expect(g).toContain("2026-11-03 화 = 다음 주 화요일");
    expect(g).toContain("2026-11-09 월 = 다다음 주 월요일");
    expect(g).toContain("2026-10-31 토 = 내일, 이번 주 토요일");
    expect(g).toContain("2026-10-30 금 = 오늘, 이번 주 금요일");
    expect(g).toContain("2026-10-29 목 = 어제, 이번 주 목요일");
    expect(g).toContain("2026-10-28 수 = 그저께, 이번 주 수요일");
    expect(g).toContain("2026-10-26 월 = 이번 주 월요일");
    expect(g).toContain("2026-10-23 금 = 지난 주 금요일");
  });
  it("일요일 예외: 이번 주 일요일=돌아오는 일요일, 다음 주 일요일=그다음", () => {
    expect(g).toContain("2026-11-01 일 = 모레, 이번 주 일요일");
    expect(g).toContain("2026-11-08 일 = 다음 주 일요일");
    expect(g).toContain("2026-11-15 일 = 다다음 주 일요일(확인 대기)");
    expect(g).toContain("2026-10-25 일 = 이번 주 첫날 일요일");
    expect(g).toContain("2026-10-18 일 = 지난 주 일요일(지난 주 첫날)(확인 대기)");
  });
  it("표는 오늘-14일 ~ 오늘+27일 안", () => {
    expect(g).not.toContain("2026-10-10");
    expect(g).not.toContain("2026-11-30 월 =");
  });
  it("요일만: 다가오는 날(오늘 포함) / 과거형(오늘 제외)", () => {
    expect(g).toContain("- 토요일 → 2026-10-31 / 과거형 2026-10-24");
    expect(g).toContain("- 금요일 → 2026-10-30(오늘) / 과거형 2026-10-23");
    expect(g).toContain("- 일요일 → 2026-11-01 / 과거형 2026-10-25");
  });
  it("주·주말 범위", () => {
    expect(g).toContain("이번 주 = 2026-10-25 ~ 2026-10-31, 다음 주 = 2026-11-01 ~ 2026-11-07, 지난 주 = 2026-10-18 ~ 2026-10-24");
    expect(g).toContain("이번 주말 = 2026-10-31 ~ 2026-11-01, 다음 주말 = 2026-11-07 ~ 2026-11-08");
  });
  it("달: 2월 다가오는 = 2027, 과거형 = 2026", () => {
    expect(g).toContain("- 2월 → 2027-02-01~2027-02-28 / 과거형 2026-02-01~2026-02-28");
    expect(g).toContain("- 10월 → 2026-10-01~2026-10-31 / 과거형 2026-10-01~2026-10-31");
    expect(g).toContain("- 11월 → 2026-11-01~2026-11-30 / 과거형 2025-11-01~2025-11-30");
    expect(g).toContain("이번 달 = 2026-10-01~2026-10-31, 다음 달 = 2026-11-01~2026-11-30, 지난 달 = 2026-09-01~2026-09-30");
  });
  it("연도 없는 날짜 경계 문장", () => {
    expect(g).toContain("그 외: 10-30~12-31은 2026년, 01-01~10-29는 2027년 / 과거형: 01-01~10-29는 2026년, 10-30~12-31은 2025년");
  });
});

describe("buildDateGuide: 경계 기준일", () => {
  it("일요일 당일(2026-11-01): 이번 주 = 11-01~11-07, 이번 주 일요일 = 오늘, 주말은 되묻기", () => {
    const g = buildDateGuide("2026-11-01");
    expect(g).toContain("이번 주 = 2026-11-01 ~ 2026-11-07");
    expect(g).toContain("2026-11-01 일 = 오늘, 이번 주 일요일");
    expect(g).toContain("2026-11-08 일 = 다음 주 일요일");
    expect(g).toContain("이번 주말 = 되묻기");
    expect(g).toContain("- 일요일 → 2026-11-01(오늘) / 과거형 2026-10-25");
    expect(g).toContain("2026-11-07 토 = 이번 주 토요일");
    expect(g).not.toContain("이번 주 첫날 일요일");
  });
  it("수요일(2026-11-04): 이번 주말 = 토 + 돌아오는 일", () => {
    const g = buildDateGuide("2026-11-04");
    expect(g).toContain("이번 주말 = 2026-11-07 ~ 2026-11-08, 다음 주말 = 2026-11-14 ~ 2026-11-15");
    expect(g).toContain("2026-11-08 일 = 이번 주 일요일");
  });
  it("연초(2027-01-05): 12월은 다가오는=2027, 과거형=2026, 연도 경계 문장", () => {
    const g = buildDateGuide("2027-01-05");
    expect(g).toContain("- 12월 → 2027-12-01~2027-12-31 / 과거형 2026-12-01~2026-12-31");
    expect(g).toContain("그 외: 01-05~12-31은 2027년, 01-01~01-04는 2028년 / 과거형: 01-01~01-04는 2027년, 01-05~12-31은 2026년");
  });
  it("1월 1일 당일은 경계 없이 한 해", () => {
    expect(buildDateGuide("2027-01-01")).toContain("그 외: 01-01~12-31은 2027년 / 과거형: 01-01~12-31은 2026년");
  });
  it("연말(2026-12-31): 내일은 다음 해", () => {
    expect(buildDateGuide("2026-12-31")).toContain("2027-01-01 금 = 내일, 이번 주 금요일");
  });
  it("같은 입력은 같은 출력, 길이는 4000자 이내", () => {
    expect(buildDateGuide("2026-10-30")).toBe(buildDateGuide("2026-10-30"));
    expect(buildDateGuide("2026-10-30").length).toBeLessThan(4000);
  });
});
