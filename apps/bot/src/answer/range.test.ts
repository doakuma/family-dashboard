import { describe, expect, it } from "vitest";
import { MAX_SPAN_DAYS, isPastQuestion, resolveRange } from "./range";

const ok = (text: string, today: string) => {
  const r = resolveRange(text, today);
  return r && "from" in r ? [r.from, r.to] : r;
};

describe("resolveRange: 기준일 2026-10-30(금)", () => {
  const T = "2026-10-30";
  it.each([
    ["오늘 뭐 있어?", "2026-10-30", "2026-10-30"],
    ["내일 일정", "2026-10-31", "2026-10-31"],
    ["모레 뭐 해?", "2026-11-01", "2026-11-01"],
    ["내일모레 뭐 있어", "2026-11-01", "2026-11-01"],
    ["어제 뭐 있었어", "2026-10-29", "2026-10-29"],
    ["이번 주 토요일 뭐 있어?", "2026-10-31", "2026-10-31"],
    ["이번주 토요일", "2026-10-31", "2026-10-31"],
    ["이번 주 월요일", "2026-10-26", "2026-10-26"],
    ["다음 주 화요일 일정", "2026-11-03", "2026-11-03"],
    ["다다음 주 월요일", "2026-11-09", "2026-11-09"],
    ["지난 주 금요일", "2026-10-23", "2026-10-23"],
    ["이번 주 뭐 있어?", "2026-10-25", "2026-10-31"],
    ["다음 주 일정", "2026-11-01", "2026-11-07"],
    ["이번 주말에 뭐 있어", "2026-10-31", "2026-11-01"],
    ["다음 주말", "2026-11-07", "2026-11-08"],
    ["주말 일정", "2026-10-31", "2026-11-01"],
    ["일요일에 뭐 있어", "2026-11-01", "2026-11-01"],
    ["이번 주 일요일", "2026-11-01", "2026-11-01"],
    ["다음 주 일요일", "2026-11-08", "2026-11-08"],
    ["지난 주 일요일", "2026-10-25", "2026-10-25"],
    ["지난 주말", "2026-10-24", "2026-10-25"],
    ["금요일 일정", "2026-10-30", "2026-10-30"],
    ["11월 3일 일정", "2026-11-03", "2026-11-03"],
    ["11/3 일정", "2026-11-03", "2026-11-03"],
    ["10월 24일 뭐 했지", "2026-10-24", "2026-10-24"],
    ["11월에 뭐 있어", "2026-11-01", "2026-11-30"],
    ["이번 달 일정", "2026-10-01", "2026-10-31"],
    ["다음 달 일정", "2026-11-01", "2026-11-30"],
    ["2월 일정", "2027-02-01", "2027-02-28"],
    ["1월 5일", "2027-01-05", "2027-01-05"],
    ["오늘이랑 내일 일정", "2026-10-30", "2026-10-31"],
  ])("%s", (text, from, to) => {
    expect(ok(text, T)).toEqual([from, to]);
  });

  it("날짜 표현이 없으면 undefined", () => {
    expect(resolveRange("뭐 있어?", T)).toBeUndefined();
    expect(resolveRange("치과 언제야?", T)).toBeUndefined();
  });

  it("없는 날짜(2월 30일)는 범위로 쓰지 않는다", () => {
    expect(resolveRange("2월 30일", T)).toBeUndefined();
  });

  it("너무 긴 범위는 too_long", () => {
    expect(resolveRange("오늘이랑 1월 5일 일정", T)).toEqual({ error: "too_long" });
    expect(MAX_SPAN_DAYS).toBe(62);
  });
});

describe("주 경계 (주는 일요일~토요일)", () => {
  it("일요일 당일: 이번 주는 오늘~토요일, 이번 주 일요일은 오늘, 다음 주 일요일은 +7", () => {
    const T = "2026-11-01";
    expect(ok("이번 주 일정", T)).toEqual(["2026-11-01", "2026-11-07"]);
    expect(ok("이번 주 일요일", T)).toEqual(["2026-11-01", "2026-11-01"]);
    expect(ok("다음 주 일요일", T)).toEqual(["2026-11-08", "2026-11-08"]);
    expect(ok("지난 주 일요일", T)).toEqual(["2026-10-25", "2026-10-25"]);
    expect(ok("이번 주 토요일", T)).toEqual(["2026-11-07", "2026-11-07"]);
    expect(ok("지난 주 토요일", T)).toEqual(["2026-10-31", "2026-10-31"]);
    expect(ok("다음 주 월요일", T)).toEqual(["2026-11-09", "2026-11-09"]);
    expect(ok("다음 주 일정", T)).toEqual(["2026-11-08", "2026-11-14"]);
    expect(ok("지난 주", T)).toEqual(["2026-10-25", "2026-10-31"]);
  });
  it("일요일 당일의 주말: 그냥 주말·이번 주말은 오늘만(진행 중), 다음 주말은 다음 주 토~일", () => {
    expect(ok("주말", "2026-11-01")).toEqual(["2026-11-01", "2026-11-01"]);
    expect(ok("이번 주말", "2026-11-01")).toEqual(["2026-11-01", "2026-11-01"]);
    expect(ok("다음 주말", "2026-11-01")).toEqual(["2026-11-14", "2026-11-15"]);
  });
  it("토요일 당일: 이번 주는 어제까지 포함한 일~오늘, 이번 주 일요일은 내일", () => {
    const T = "2026-10-31";
    expect(ok("이번 주 일정", T)).toEqual(["2026-10-25", "2026-10-31"]);
    expect(ok("이번 주 토요일", T)).toEqual(["2026-10-31", "2026-10-31"]);
    expect(ok("이번 주 일요일", T)).toEqual(["2026-11-01", "2026-11-01"]);
    expect(ok("다음 주 일요일", T)).toEqual(["2026-11-08", "2026-11-08"]);
    expect(ok("지난 주 일요일", T)).toEqual(["2026-10-25", "2026-10-25"]);
    expect(ok("다음 주 일정", T)).toEqual(["2026-11-01", "2026-11-07"]);
    expect(ok("주말 일정", T)).toEqual(["2026-10-31", "2026-11-01"]);
    expect(ok("이번 주말", T)).toEqual(["2026-10-31", "2026-11-01"]);
    expect(ok("다음 주말", T)).toEqual(["2026-11-07", "2026-11-08"]);
  });
  it("월요일 기준: 이번 주는 어제(일요일)~토요일, 지난 주 일요일은 어제", () => {
    const T = "2026-11-02";
    expect(ok("이번 주 일정", T)).toEqual(["2026-11-01", "2026-11-07"]);
    expect(ok("이번 주 일요일", T)).toEqual(["2026-11-08", "2026-11-08"]);
    expect(ok("지난 주 일요일", T)).toEqual(["2026-11-01", "2026-11-01"]);
    expect(ok("이번 주 월요일", T)).toEqual(["2026-11-02", "2026-11-02"]);
  });
});

describe("연도 없는 날짜·요일: 과거형은 지난 날, 그 외는 다가오는 날", () => {
  const T = "2026-10-30"; // 금
  it("과거형 단서", () => {
    for (const q of ["뭐 했어?", "뭐 했지", "뭐 있었지?", "어디 갔어", "누가 왔어", "뭐 먹었어", "뭐 봤더라", "일정 있었나"]) {
      expect(isPastQuestion(q), q).toBe(true);
    }
    for (const q of ["뭐 있어?", "일정 알려줘", "언제야?", "치과 가기로 했지?", "뭐 해?"]) expect(isPastQuestion(q), q).toBe(false);
  });
  it.each([
    ["5월 1일 뭐 했어?", "2026-05-01"],
    ["5월 1일 일정", "2027-05-01"],
    ["10월 24일 뭐 했지", "2026-10-24"],
    ["10월 24일 일정", "2027-10-24"],
    ["11/3 뭐 있었어", "2025-11-03"],
    ["11/3 일정", "2026-11-03"],
    ["12월 25일 갔어?", "2025-12-25"],
    ["12월 25일 뭐 있어?", "2026-12-25"],
  ])("%s", (text, d) => expect(ok(text, T)).toEqual([d, d]));
  it("오늘 날짜 자체: 미래형은 오늘 포함, 과거형은 오늘 제외(지난해)", () => {
    expect(ok("10월 30일 일정", T)).toEqual(["2026-10-30", "2026-10-30"]);
    expect(ok("10월 30일 뭐 했어", T)).toEqual(["2025-10-30", "2025-10-30"]);
  });
  it("연말을 넘는 연도 없는 날짜", () => {
    expect(ok("1월 3일 일정", "2026-12-31")).toEqual(["2027-01-03", "2027-01-03"]);
    expect(ok("12월 28일 뭐 했어", "2027-01-05")).toEqual(["2026-12-28", "2026-12-28"]);
    expect(ok("12월 28일 일정", "2027-01-05")).toEqual(["2027-12-28", "2027-12-28"]);
    expect(ok("1월 1일 뭐 있었어", "2027-01-01")).toEqual(["2026-01-01", "2026-01-01"]);
  });
  it("2월 29일은 윤년을 찾아간다", () => {
    expect(ok("2월 29일 일정", "2027-12-01")).toEqual(["2028-02-29", "2028-02-29"]);
    expect(ok("2월 29일 뭐 했어", "2027-12-01")).toEqual(["2024-02-29", "2024-02-29"]);
  });
  it("M월: 이번 달이면 이번 달 그대로(과거형이어도), 아니면 과거형은 지난 달·그 외는 다가오는 달", () => {
    expect(ok("10월 일정", T)).toEqual(["2026-10-01", "2026-10-31"]);
    expect(ok("10월에 뭐 했어", T)).toEqual(["2026-10-01", "2026-10-31"]);
    expect(ok("9월 일정", T)).toEqual(["2027-09-01", "2027-09-30"]);
    expect(ok("9월에 뭐 했어", T)).toEqual(["2026-09-01", "2026-09-30"]);
    expect(ok("11월 일정", T)).toEqual(["2026-11-01", "2026-11-30"]);
    expect(ok("11월에 뭐 했어", T)).toEqual(["2025-11-01", "2025-11-30"]);
    expect(ok("12월", "2027-01-05")).toEqual(["2027-12-01", "2027-12-31"]);
    expect(ok("12월 뭐 했어", "2027-01-05")).toEqual(["2026-12-01", "2026-12-31"]);
  });
  it("요일만 (금요일 당일)", () => {
    expect(ok("금요일 일정", T)).toEqual(["2026-10-30", "2026-10-30"]); // 미래형은 오늘 포함
    expect(ok("금요일에 뭐 했어", T)).toEqual(["2026-10-23", "2026-10-23"]); // 과거형은 오늘 제외
    expect(ok("토요일 일정", T)).toEqual(["2026-10-31", "2026-10-31"]);
    expect(ok("토요일에 뭐 했어", T)).toEqual(["2026-10-24", "2026-10-24"]);
    expect(ok("일요일에 뭐 있었지", T)).toEqual(["2026-10-25", "2026-10-25"]);
    expect(ok("목요일에 뭐 했지", T)).toEqual(["2026-10-29", "2026-10-29"]);
  });
  it("요일만 (일요일·토요일 당일)", () => {
    expect(ok("일요일 일정", "2026-11-01")).toEqual(["2026-11-01", "2026-11-01"]);
    expect(ok("일요일에 뭐 했어", "2026-11-01")).toEqual(["2026-10-25", "2026-10-25"]);
    expect(ok("토요일 일정", "2026-10-31")).toEqual(["2026-10-31", "2026-10-31"]);
    expect(ok("토요일에 뭐 했어", "2026-10-31")).toEqual(["2026-10-24", "2026-10-24"]);
  });
  it("주 수식이 붙은 요일은 과거형이어도 그 주 기준", () => {
    expect(ok("이번 주 월요일에 뭐 했어", T)).toEqual(["2026-10-26", "2026-10-26"]);
  });
  it("옵션 past로 강제할 수 있다", () => {
    expect(resolveRange("5월 1일", T, { past: true })).toEqual({ from: "2026-05-01", to: "2026-05-01" });
    expect(resolveRange("5월 1일 뭐 했어", T, { past: false })).toEqual({ from: "2027-05-01", to: "2027-05-01" });
  });
});

describe("월말·연말 넘김", () => {
  const T = "2026-12-31";
  it("내일·다음 주·다음 달이 해를 넘는다", () => {
    expect(ok("내일", T)).toEqual(["2027-01-01", "2027-01-01"]);
    expect(ok("모레", T)).toEqual(["2027-01-02", "2027-01-02"]);
    expect(ok("다음 주 월요일", T)).toEqual(["2027-01-04", "2027-01-04"]);
    expect(ok("다음 주 일요일", T)).toEqual(["2027-01-10", "2027-01-10"]);
    expect(ok("이번 주", T)).toEqual(["2026-12-27", "2027-01-02"]);
    expect(ok("다음 달", T)).toEqual(["2027-01-01", "2027-01-31"]);
    expect(ok("이번 달", T)).toEqual(["2026-12-01", "2026-12-31"]);
    expect(ok("1월 5일", T)).toEqual(["2027-01-05", "2027-01-05"]);
  });
  it("월말: 10월 31일 기준 내일은 11월 1일, 2월 말은 평년·윤년을 따른다", () => {
    expect(ok("내일", "2026-10-31")).toEqual(["2026-11-01", "2026-11-01"]);
    expect(ok("다음 달", "2027-01-15")).toEqual(["2027-02-01", "2027-02-28"]);
    expect(ok("다음 달", "2028-01-15")).toEqual(["2028-02-01", "2028-02-29"]);
  });
});

describe("연도를 말하면 그대로 읽는다", () => {
  const T = "2026-10-30";
  it.each([
    ["2027년 1월 5일", "2027-01-05", "2027-01-05"],
    ["2025년 3월 2일 뭐 했지", "2025-03-02", "2025-03-02"],
    ["2027-01-05 일정", "2027-01-05", "2027-01-05"],
    ["2027년 2월 일정", "2027-02-01", "2027-02-28"],
    ["2025년 12월 뭐 했어", "2025-12-01", "2025-12-31"],
    ["2026년 5월 1일 일정", "2026-05-01", "2026-05-01"],
  ])("%s", (text, from, to) => expect(ok(text, T)).toEqual([from, to]));
});

describe("이어지는 요일은 앞의 주 수식을 물려받는다", () => {
  const T = "2026-10-30";
  it.each([
    ["다음 주 토요일이랑 일요일", "2026-11-07", "2026-11-08"],
    ["다음 주 토요일, 일요일 뭐 있어", "2026-11-07", "2026-11-08"],
    ["다음 주에 토요일", "2026-11-07", "2026-11-07"],
    ["다음 주 토요일과 일요일", "2026-11-07", "2026-11-08"],
    ["이번 주 월요일이랑 화요일", "2026-10-26", "2026-10-27"],
  ])("%s", (text, from, to) => expect(ok(text, T)).toEqual([from, to]));
  it("떨어진 날짜들은 하나로 못 정해 ambiguous", () => {
    expect(resolveRange("오늘이랑 모레", T)).toEqual({ error: "ambiguous" });
    expect(resolveRange("다음 주 월요일이랑 수요일", T)).toEqual({ error: "ambiguous" });
  });
});
